public class logicalOpeator {
    public static void main(String[] args) {

        // &&  (and) opretor

        int a =22;
        int b =34;
        int c =32;
        int d =322;
        boolean e =(a<b ) && (c<d); 
        System.out.println(e);  //true

        // || (or) operator

        int f = 22;
        int g = 34;
        int h = 32;
        int i = 322;
        boolean j = (f < g) || (h > i); 
        System.out.println(j);    //true

    }
}
